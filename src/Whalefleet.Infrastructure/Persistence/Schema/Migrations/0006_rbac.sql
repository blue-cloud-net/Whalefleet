-- ============================================================================
-- 0006_rbac.sql —— 作用域化的 User → Role → Permission
--
-- 本版把授权落地为标准的角色模型：
--   * roles              增加「角色携带一组权限」这一维度（role_permissions）
--   * user_role_assignments  用户 ↔ 角色改为多对多，且**带作用域**
--   * users              去掉 role_id（角色不再是用户「拥有」的东西，而是被「分配」的）
--
-- 三张表的分工：
--   roles                 角色是什么（可运行时增删的数据）
--   role_permissions      这个角色能做什么（静态目录的子集）
--   user_role_assignments 谁在**哪个范围内**拥有这个角色
--
-- 「权限目录」本身不建表：「本版本有没有这个功能」是编译期事实，
-- 放进表里只会让运行时可配的角色逐渐偏离代码真正能强制的范围。
-- role_permissions.permission 因此没有外键指向任何目录表——
-- 它存的是 `domain.level` 文本（如 `container.write`），由 Core/Permissions/Permission.cs 校验。
--
-- 为什么不回填旧授权数据：本迭代从未产出正式发布的 tag，不存在需要迁移的生产数据。
-- 位掩码 → 角色名还是一次有损映射（read/write/admin 三档无法无损落到若干角色的并集上），
-- 与其悄悄降级，不如直接丢弃并在应用层重新分配。
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 1. role_permissions —— 角色携带的权限集
-- ---------------------------------------------------------------------------
CREATE TABLE role_permissions
(
    role_id                TEXT    NOT NULL REFERENCES roles (id),
    permission             TEXT    NOT NULL,

    -- 只有审计、没有业务主键：这是角色权限的纯连接表，
    -- 删角色时由外键与「删除前检查分配」两层处理，不需要软删除历史
    creation_time          TEXT    NOT NULL,
    creator_id             TEXT    NOT NULL,

    -- 覆盖式更新（ReplacePermissionsAsync）不做差量审计：
    -- 角色权限的「历史版本」在安全审计里没有意义——
    -- 要回答的是「现在谁能干什么」，而不是「曾经谁能干什么」。
    -- 保留这两列是为了与其他表列序一致、INSERT 可以复用同一段参数拼装。
    last_modification_time TEXT    NULL,
    last_modifier_id       TEXT    NOT NULL,

    PRIMARY KEY (role_id, permission)
);

-- 权限矩阵按角色取全集：(role_id) 走主键前缀，无需额外索引

-- ---------------------------------------------------------------------------
-- 2. user_role_assignments —— 带作用域的用户-角色分配
-- ---------------------------------------------------------------------------
CREATE TABLE user_role_assignments
(
    id                     TEXT    NOT NULL PRIMARY KEY,
    user_id                TEXT    NOT NULL REFERENCES users (id),
    role_id                TEXT    NOT NULL REFERENCES roles (id),

    -- NULL = 全局分配；非空 = 只在该主机上生效。
    --
    -- ⚠️ 全局分配只贡献角色的 **Global** 权限；主机分配的 Global 权限被忽略。
    --    否则「把 admin 分配到某台主机」会变成一次静默的系统级提权——
    --    这是本模型里最容易写错、后果最严重的一条规则。
    host_id                TEXT    NULL REFERENCES hosts (id),

    creation_time          TEXT    NOT NULL,
    creator_id             TEXT    NOT NULL,
    last_modification_time TEXT    NULL,
    last_modifier_id       TEXT    NOT NULL,
    is_deleted             INTEGER NOT NULL DEFAULT 0,
    deletion_time          TEXT    NULL,
    deleter_id             TEXT    NOT NULL
);

-- ⚠️ 唯一索引必须用 **COALESCE(host_id, '')** 而不是裸 host_id：
--    SQLite 的唯一索引**不去重 NULL**（每个 NULL 都被视为互不相同），
--    用裸列的话「同一个全局角色」能被无限次重复分配，
--    而应用层的幂等 upsert 只是"友好"，数据库层才是真正的约束。
CREATE UNIQUE INDEX ux_user_role_assignments
    ON user_role_assignments (user_id, role_id, COALESCE(host_id, ''))
    WHERE is_deleted = 0;

-- 鉴权热路径：一次查询拿全该用户的分配。必须走索引，否则每个请求都是全表扫。
CREATE INDEX ix_user_role_assignments_user
    ON user_role_assignments (user_id)
    WHERE is_deleted = 0;

-- 主机视角：「谁能访问这台机器」
CREATE INDEX ix_user_role_assignments_host
    ON user_role_assignments (host_id)
    WHERE is_deleted = 0 AND host_id IS NOT NULL;

