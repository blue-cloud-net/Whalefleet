-- ---------------------------------------------------------------------------
-- 5. users：去掉 role_id
--
-- SQLite 的 ALTER TABLE 不能删列，只能走官方的「建新表 → 搬数据 → 删旧表 → 改名」。
-- 外键必须先关掉：DROP TABLE users 在外键打开时会把引用它的行一起处理掉。
--
-- 上一步已经把 role_id 读进 user_role_assignments，且两份数据的 user_id 完全一致，
-- 因此重建后分配记录的外键仍然指向真实存在的用户。
-- ---------------------------------------------------------------------------
PRAGMA foreign_keys = OFF;

