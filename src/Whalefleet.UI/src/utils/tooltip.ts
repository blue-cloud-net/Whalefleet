/**
 * 悬浮提示的延迟弹出时间（毫秒）。
 *
 * ## 为什么不能是 0（Element Plus 的默认值）
 * 表格里每一行都有悬浮提示（名称、镜像名、ID…）。鼠标扫过一列时提示**逐个弹出**，
 * 0 延迟下鼠标划过的那一行会闪出一串提示框，读者的注意力被反复拽走，
 * 反而看不清自己在看哪一行——提示从「补充信息」变成了「干扰」。
 *
 * 500ms 是「停下来的意图」与「路过」的分界：手停下来看，才弹出。
 *
 * ⚠️ **只给「补充信息」类的提示加延迟**：图标按钮（显示列、刷新…）的提示是
 * **唯一**说明该按钮干什么的东西，延迟会让它显得没有反应；
 * 但同样不能是 0——0 延迟下划过工具栏就是一串闪烁。
 */
export const TIP_DELAY_MS = 500
