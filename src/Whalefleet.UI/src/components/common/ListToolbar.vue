<script setup lang="ts">
import { useI18n } from 'vue-i18n'

/**
 * 列表页工具条：搜索 / 筛选 + 常驻批量动作 + 右侧附加操作。
 *
 * ## 为什么批量动作**常驻**而不是「选中后才出现」
 * 早先的做法是选中一行才浮出一条批量操作条（旧版 `BatchActionBar`）。
 * 那种模型的毛病是**入口不可发现**：用户得先知道「勾选行之后会出现一条能批量启动的东西」，
 * 而页面上没有任何东西提示这件事。
 *
 * 常驻 + 未选中时禁用是更好的折中：按钮一直在那儿（用户知道这个页面支持批量操作），
 * 但没勾选时点不动（不会让人怀疑页面坏了）。
 *
 * ## 为什么动作由调用方给
 * 容器页是启停 / 重启 / 删除，镜像页只有删除，主机页只有批量打标——
 * 文案、图标、危险等级都不一样。内置就得在这写一堆 if。
 *
 * ## 「已选 N」为什么挪到**最左**、且占**固定槽位**
 *
 * 它原本跟在批量按钮后面（与批量按钮同组）。问题出在**宽度会变**：
 * 勾选一个容器 → 「已选 1 项」+「取消选择」凭空多出来 →
 * 整条工具条的内容宽度变了 → 工具条是右对齐的，于是**所有控件整体平移**。
 * 实测一次勾选让五个批量按钮整体左移 130 多像素——用户看到的就是「按钮抖了一下」。
 *
 * 两件事一起做才彻底解决：
 * ① **挪到最左**：它是「状态读数」，不是控件，不该插在控件流中间；
 * ② **固定槽位**：槽位永远占着宽度，计数为 0 时留空。
 * 这样勾选前后工具条宽度**完全不变**，任何控件都不再移动。
 *
 * > ⚠️ 槽位是 `min-w-[4rem]` 而不是 `w-*`：计数到三位数（已选 100 项）时
 * > 文字要能撑开，而不是被裁掉。
 *
 * ## 为什么没有「取消选择」按钮
 * 取消选区有三条现成的路：表头的「全选」复选框（再点一次即全不选）、
 * 每行的复选框、以及批量动作执行后各页自己清空。
 * 为此常驻一个按钮不值——它把「已选 N」和「清空」挤在一起，
 * 让状态读数看起来像个控件，反而更容易误触。
 *
 * ## 三组元素必须分开（不是审美问题）
 * 工具条里其实有三件互不相干的事：
 *
 * | 组 | 回答的问题 | 元素 |
 * |----|-----------|------|
 * | 筛选 | 我要找哪几条 | 搜索框、状态下拉、命中计数 |
 * | 批量 | 要对这几条做什么 | 批量动作 |
 * | 页面 | 这一页本身怎么刷新 / 怎么显示 | 刷新、列设置 |
 *
 * 「已选 N」是**状态读数**而非控件，它单独占工具条最左的一个固定槽位。
 *
 * 挤成一排时批量按钮会被读成搜索框的附属品——尤其批量是**图标按钮**的时候，
 * 视觉上更像筛选栏的一部分。所以组间给 `gap-x-4` 留白 + 一条 1px 竖线。
 *
 * ## 批量动作用「图标 + 文字」，不是纯图标
 * 行内动作图标化是对的（一行四五个，配文字会把表格撑宽），但工具条上的批量动作
 * 恰恰相反：它是「这一页支持批量操作」的唯一提示，也是最高频的那几个动作。
 * 纯图标时用户得逐个悬停去确认哪个是启动、哪个是删除——高频动作不该靠猜。
 * `IconActionButton` 的 `show-label` 就是这个模式（文字写在按钮上，tooltip 只留禁用原因）。
 *
 * ## 批量动作之间用 `gap-1`（读成一个按钮组）
 * 一排同类按钮应当读成一个**按钮组**（紧凑），而不是一串互不相干的按钮。
 */
withDefaults(
  defineProps<{
    /**
     * 已选中的行数。
     *
     * ⚠️ **不传 = 该列表不支持批量选择**：计数槽位整个不渲染（不留空位）。
     * 传了（哪怕是 0）就渲染那个**恒定宽度**的槽位——
     * 见文件头「已选 N 为什么挪到最左、且占固定槽位」。
     */
    selectedCount?: number
    /** 批量操作执行中：禁用全部批量动作 */
    busy?: boolean
  }>(),
  { busy: false }
)

const { t } = useI18n()
</script>

<template>
  <div class="flex flex-wrap items-center justify-end gap-x-4 gap-y-2">
    <!--
      第 0 组：**已选计数**（最左）。

      ⚠️ **槽位恒定宽度**：`selectedCount` 为 0 时留空而不是删掉这个元素——
      删掉会让工具条宽度变化，所有控件跟着平移（勾一下就抖一下）。
      宽度用 `min-w-[4rem]`：三位数（已选 100 项）时文字要能撑开。
    -->
    <span
      v-if="selectedCount !== undefined"
      class="min-w-[4rem] shrink-0 text-xs font-medium text-content-strong"
    >
      {{
        selectedCount > 0 ? t('common.selected', { count: selectedCount }) : ''
      }}
    </span>

    <!-- 第 1 组：筛选——搜索框、状态下拉、命中计数 -->
    <div class="flex flex-wrap items-center gap-2">
      <slot name="filters" />
    </div>

    <!--
      组间分隔线。

      ⚠️ **只在 `md` 以上显示**：窄屏下工具条会折行，竖线若正好落在新行的行首，
      看着像多刷了一道「|」，反而不如只靠 `gap-x-4` 的留白。

      ⚠️ 这里是**结构性**分隔，不是装饰：三组元素回答的是三个不同问题——
      「我要找哪几条」「要对它们做什么」「这一页本身怎么刷新 / 怎么显示」。
      挤在一起时批量按钮会被读成搜索框的附属品。
    -->
    <span
      v-if="$slots.batch"
      class="hidden h-4 w-px shrink-0 bg-line-subtle md:block"
      aria-hidden="true"
    />

    <!--
      第 2 组：批量动作。
      「已选 N」不在这一组里——它挪到了最左（见文件头）。
    -->
    <div v-if="$slots.batch" class="flex flex-wrap items-center gap-1">
      <!--
        批量动作：**常驻**。
        槽位参数给出 count 与 busy，调用方据此禁用——
        「没勾选时点不动」是这里的关键，禁用原因由调用方写进 tooltip。

        按钮之间的间距压到 `gap-1`（4px）：批量动作是**一排同类按钮**，
        它们该读成一个整体（像按钮组），而不是一串互不相干的按钮。
      -->
      <slot name="batch" :count="selectedCount ?? 0" :busy="busy" />
    </div>

    <span
      v-if="$slots.extra"
      class="hidden h-4 w-px shrink-0 bg-line-subtle md:block"
      aria-hidden="true"
    />

    <!-- 第 3 组：页面级附加操作——刷新、列设置 -->
    <div class="flex items-center gap-1">
      <slot name="extra" />
    </div>
  </div>
</template>
